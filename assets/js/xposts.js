/* ============================================================
   SuccuChan v2 — HOME "LATEST ON X"
   Renders the latest posts as the site's own cards from
   assets/data/x-posts.json (generated by tools/x_latest_to_site.py).
   No X widget script: shows for every visitor (logged out, private
   windows, tracking protection) and sets no cookies.
   ============================================================ */
(function () {
  var sec = document.querySelector("[data-xposts]");
  if (!sec) return;
  var grid = sec.querySelector("[data-xposts-grid]");

  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"]/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c];
    });
  }
  // escaped text with #hashtags / URLs softly highlighted (the whole card is the link)
  function fmtText(t) {
    return esc(t)
      .replace(/(^|[\s　])([#＃][^\s　#＃]+)/g, '$1<span class="x-tag">$2</span>')
      .replace(/https?:\/\/[^\s<]+/g, function (u) {
        return '<span class="x-link">' + u.replace(/^https?:\/\/(www\.)?/, "").slice(0, 34) + (u.length > 44 ? "…" : "") + "</span>";
      });
  }
  function fmtDate(iso) {
    var d = new Date(iso);
    if (isNaN(d)) return "";
    return d.toLocaleString("ja-JP", { timeZone: "Asia/Tokyo", month: "numeric", day: "numeric", hour: "2-digit", minute: "2-digit" });
  }
  var X_LOGO = '<svg class="x-logo" viewBox="0 0 24 24" aria-hidden="true"><path fill="currentColor" d="M18.244 2.25h3.308l-7.227 8.26 8.502 11.24H16.17l-5.214-6.817L4.99 21.75H1.68l7.73-8.835L1.254 2.25H8.08l4.713 6.231zm-1.161 17.52h1.833L7.084 4.126H5.117z"/></svg>';

  function card(p, acct) {
    if (typeof p === "string") p = { url: p }; // legacy: URL only
    var m = (p.media || [])[0];
    var media = m ? '<span class="x-media"><img src="' + esc(m.src) + '" alt="' + esc(m.alt) + '" loading="lazy" decoding="async" referrerpolicy="no-referrer">' +
      (m.type === "video" || m.type === "animated_gif" ? '<span class="x-play" aria-hidden="true"></span>' : "") +
      ((p.media || []).length > 1 ? '<span class="x-more">+' + (p.media.length - 1) + "</span>" : "") + "</span>" : "";
    return '<a class="x-card" href="' + esc(p.url) + '" target="_blank" rel="noopener">' +
      '<span class="x-head">' +
        (acct.avatar ? '<img class="x-av" src="' + esc(acct.avatar) + '" alt="" loading="lazy" referrerpolicy="no-referrer">' : '<span class="x-av"></span>') +
        '<span class="x-id"><b>' + esc(acct.name || "SuccuChan") + "</b><span>@" + esc(acct.username || "SuccuChan_AI") + "</span></span>" +
        X_LOGO +
      "</span>" +
      (p.text ? '<span class="x-text">' + fmtText(p.text) + "</span>" : '<span class="x-text">Xでこのポストを見る</span>') +
      media +
      '<span class="x-foot"><time datetime="' + esc(p.created_at || "") + '">' + fmtDate(p.created_at) + "</time>" +
        '<span class="x-go">Xで見る <span aria-hidden="true">&rarr;</span></span></span>' +
    "</a>";
  }

  fetch("assets/data/x-posts.json", { cache: "no-cache" })
    .then(function (r) { return r.json(); })
    .then(function (data) {
      var posts = (data.posts || []).filter(Boolean).slice(0, 3);
      if (!posts.length) return; // nothing to show: keep the section hidden
      var more = sec.querySelector("[data-xposts-more]");
      if (more && data.profile) more.href = data.profile;
      var acct = data.account || {};
      grid.innerHTML = posts.map(function (p) { return card(p, acct); }).join("");
      sec.hidden = false;
    })
    .catch(function (e) { console.error("x-posts load failed", e); });
})();
